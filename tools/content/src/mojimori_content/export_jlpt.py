"""Export the JLPT kanji list the offline app (durtles/) uses for its JLPT curriculum.

Levels come from Jonathan Waller's unofficial lists (jlpt_new). Kanji missing there fall back
to KANJIDIC2's old four-level JLPT field (old 4 -> N5, 3 -> N4, 2 -> N3, 1 -> N1), and
content/jlpt_overrides.yaml has the last word. Kanji with no level belong to the Obscure block.
"""

from __future__ import annotations

from pathlib import Path

import yaml

OLD_TO_NEW = {4: 5, 3: 4, 2: 3, 1: 1}


def merge(new_levels: dict[str, str], old_levels: dict[str, int | None],
          overrides: dict[str, str]) -> dict[str, int]:
    """kanji -> 5..1 (N5..N1); kanji without a level are left out."""
    out: dict[str, int] = {}
    for literal, old in old_levels.items():
        if old in OLD_TO_NEW:
            out[literal] = OLD_TO_NEW[old]
    for literal, lvl in new_levels.items():
        out[literal] = int(lvl[1:])
    for literal, lvl in overrides.items():
        if lvl is None or str(lvl).upper() == "OBSCURE":
            out.pop(literal, None)
        else:
            out[literal] = int(str(lvl).upper().lstrip("N"))
    return out


def export(out: Path, *, log=print) -> Path:
    from .config import CONTENT_DIR, cache_path
    from .fetch import fetch_all
    from .sources import jlpt, kanjidic2

    fetch_all(["kanjidic2", "jlpt_kanji"])
    kd = kanjidic2.parse(cache_path("kanjidic2"))
    overrides = yaml.safe_load((CONTENT_DIR / "jlpt_overrides.yaml").read_text(encoding="utf-8")) or {}
    levels = merge(jlpt.parse_kanji_levels(cache_path("jlpt_kanji")),
                   {lit: k.jlpt_old for lit, k in kd.items()}, overrides)
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8", newline="\n") as f:
        f.write("# kanji<TAB>JLPT level (5 = N5 ... 1 = N1). Generated by mojimori-content export-jlpt.\n")
        for literal, lvl in sorted(levels.items(), key=lambda kv: (-kv[1], kv[0])):
            f.write(f"{literal}\t{lvl}\n")
    counts = {n: sum(1 for v in levels.values() if v == n) for n in (5, 4, 3, 2, 1)}
    log(f"export-jlpt: {out} " + ", ".join(f"N{n} {c}" for n, c in counts.items()))
    return out
