"""Export the radical picker's data for the offline app (content/inputs/radicals.tsv).

RADKFILE (EDRDG, CC BY-SA 4.0) lists ~250 parts with their stroke counts and every kanji that
contains each one. Some parts are written there with a stand-in kanji (化 for the person radical 亻,
込 for 辶, ...) because JIS X 0208 has no character for them; DISPLAY maps those to the real form.
"""

from __future__ import annotations

from pathlib import Path

# RADKFILE stand-in -> the part as it is drawn. The rest are written as themselves.
DISPLAY: dict[str, str] = {
    "｜": "丨",
    "ノ": "丿",
    "ハ": "八",
    "化": "亻",
    "个": "𠆢",
    "并": "丷",
    "刈": "刂",
    "乞": "𠂉",
    "込": "辶",
    "尚": "⺌",
    "忙": "忄",
    "扎": "扌",
    "汁": "氵",
    "犯": "犭",
    "艾": "艹",
    "邦": "⻏",
    "阡": "⻖",
    "老": "耂",
    "杰": "灬",
    "礼": "礻",
    "疔": "疒",
    "禹": "禸",
    "初": "衤",
    "買": "罒",
    "滴": "啇",
}


def rows(radk: dict[str, tuple[int, str]]) -> list[tuple[str, int, str]]:
    """(part, stroke count, kanji containing it) in RADKFILE order, stand-ins replaced."""
    out = []
    seen: set[str] = set()
    for radical, (strokes, kanji) in radk.items():
        glyph = DISPLAY.get(radical, radical)
        if glyph in seen:
            raise ValueError(f"radkfile: part {glyph} appears twice")
        seen.add(glyph)
        # Each kanji once, in RADKFILE order.
        out.append((glyph, strokes, "".join(dict.fromkeys(kanji))))
    return out


def export(out: Path, *, log=print) -> Path:
    from .config import cache_path
    from .fetch import fetch_all
    from .sources import kradfile

    fetch_all(["radkfile"])
    data = rows(kradfile.parse_radkfile(cache_path("radkfile")))
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8", newline="\n") as f:
        f.write("# part<TAB>strokes<TAB>kanji containing it. RADKFILE (EDRDG, CC BY-SA 4.0); "
                "generated by kanjikodama-content export-radicals.\n")
        for glyph, strokes, kanji in data:
            f.write(f"{glyph}\t{strokes}\t{kanji}\n")
    log(f"export-radicals: {out} {len(data)} parts")
    return out
