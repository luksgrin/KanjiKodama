def write_status(path):
    rows = STATUS.strip("\n").split("\n")
    assert len(rows) == 24 and all(len(r) == 24 for r in rows)
    ds = []
    for y, row in enumerate(rows):
        x = 0
        while x < 24:
            if row[x] != "X":
                x += 1
                continue
            w = 1
            while x + w < 24 and row[x + w] == "X":
                w += 1
            ds.append(f"M{x},{y}h{w}v1h{-w}z")
            x += w
    with open(path, "w") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n'
                '<!-- Generated by tools/make_logo.py: notification (status bar) icon. -->\n'
                '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
                '    android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n'
                f'    <path android:fillColor="#FFFFFF" android:pathData="{"".join(ds)}"/>\n'
                "</vector>\n")


def png(size, round_):
    k = 8
    S = size * k
    img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if round_:
        d.ellipse((0, 0, S - 1, S - 1), fill=BG)
    else:
        d.rounded_rectangle((0, 0, S - 1, S - 1), radius=S // 6, fill=BG)
    margin = S * 0.12
    cell = (S - 2 * margin) / 32
    for x, y, w, ch in runs():
        d.rectangle((margin + x * cell, margin + y * cell, margin + (x + w) * cell - 1, margin + (y + 1) * cell - 1), fill=C[ch])
    return img.resize((size, size), Image.LANCZOS)


