/** One code point through {@link CLEAN_REPLACE}. */
function cleanReplace(cp: number): number {
  if (cp < 127) return cp;
  return CLEAN_REPLACE.get(cp) ?? cp;
}

/**
 * Cleans an answer: separators, controls, format characters, surrogates and unassigned
 * code points become spaces; digits and punctuation are normalized (`cleanReplace`); spaces are
 * trimmed and collapsed; then `toLowerCase(Locale.ENGLISH)` as Android does it.
 */
export function cleanString(s: string): string {
  const parts: string[] = [];
  let i = 0;
  while (i < s.length) {
    const cp = s.codePointAt(i) as number;
    const cls = cleanClass(cp);
    if (cls === CleanClass.Space) parts.push(' ');
    else if (cls === CleanClass.Replace) parts.push(String.fromCodePoint(cleanReplace(cp)));
    else parts.push(String.fromCodePoint(cp));
    i += cp >= 0x10000 ? 2 : 1;
  }
  // Trim spaces at both ends, then collapse runs of spaces (all spaces here are U+0020).
  const collapsed = parts.join('').replace(/^ +| +$/g, '').replace(/ {2,}/g, ' ');
  return androidToLowerCase(collapsed);
}

/** The OSA distance if within the length-based threshold, else MAX. */
export function getMatchScore(answer: string, reference: string): number {
  const n = reference.length;
  let threshold: number;
  if (n >= 1 && n <= 3) threshold = 0;
  else if (n === 4 || n === 5) threshold = 1;
  else if (n === 6 || n === 7) threshold = 2;
  else threshold = Math.trunc(n / 7) + 2;
  const score = osaDistance(answer, reference);
  return score <= threshold ? score : Number.MAX_SAFE_INTEGER;
}

const NO_MATCH = Number.MAX_SAFE_INTEGER;

/** `cleanString` on a reference answer; null (e.g. a meaning without text) throws NullPointerException. */
function cleanReference(reference: string | null): string {
  if (reference === null) throw new TypedError('NullPointerException', 'cleanString(null)');
  return cleanString(reference);
}

/**
 * The answer matches when its best accepted score is within the threshold
 * and no rejected answer scores better. `accepted` is iterated in order and the first best score
 * wins `matchedAnswer`, so pass the set's iteration order (see `stringSetOrder`).
 */
export function fuzzyMatches(
  answer: string,
  accepted: Iterable<string | null>,
  rejected: Iterable<string | null>,
  closeEnoughAction: CloseEnoughAction,
): AnswerVerdict {
  const cleanAnswer = cleanString(answer);

  let bestRejectedScore = NO_MATCH;
  for (const reference of rejected) {
    const score = getMatchScore(cleanAnswer, cleanReference(reference));
    if (score < bestRejectedScore) bestRejectedScore = score;
  }

  let bestAcceptedScore = NO_MATCH;
  let bestAcceptedAnswer: string | null = null;
  for (const reference of accepted) {
    const score = getMatchScore(cleanAnswer, cleanReference(reference));
    if (score < bestAcceptedScore) {
      bestAcceptedScore = score;
      bestAcceptedAnswer = reference;
    }
  }

  const matched = bestAcceptedScore < NO_MATCH && bestAcceptedScore <= bestRejectedScore;
  if (!matched) return NOK_WITHOUT_RETRY;
  if (bestAcceptedScore === 0) return makeVerdict(true, false, false, answer, bestAcceptedAnswer, null);
  switch (closeEnoughAction) {
    case 'SHAKE_AND_RETRY':
      return NOK_WITH_RETRY;
    case 'REJECT':
      return NOK_WITHOUT_RETRY;
    default:
      return makeVerdict(true, false, true, answer, bestAcceptedAnswer, null);
  }
}
