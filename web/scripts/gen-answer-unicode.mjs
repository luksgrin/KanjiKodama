// Generates src/core/answer/unicodeData.ts from the device fixture answers/unicode-android-table.json:
// the cleanString character class per code point (Character.getType on Android 16, ICU 76.1, Unicode 16)
// and the device's simple lower-case mappings. Run from web/: node scripts/gen-answer-unicode.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const table = JSON.parse(readFileSync('test/golden/answers/unicode-android-table.json', 'utf8'));
const CLASS = { keep: 0, space: 1, replace: 2 };
const starts = [];
const classes = [];
for (const c of table.cases) {
  if (!c.name.startsWith('type-')) continue;
  const cl = CLASS[c.output.class];
  if (cl === undefined) throw new Error(`unknown class in ${c.name}`);
  if (classes.length > 0 && classes[classes.length - 1] === cl) continue;
  starts.push(c.input.from);
  classes.push(cl);
}
// Code points of type UPPERCASE_LETTER, LOWERCASE_LETTER or TITLECASE_LETTER (1..3): what Android's
// CaseMapper.isFinalSigma checks with Character.isUpperCase/isLowerCase/isTitleCase (ICU u_isupper etc.).
const casedStarts = [];
let inCased = false;
for (const c of table.cases) {
  if (!c.name.startsWith('type-')) continue;
  const cased = c.output.type >= 1 && c.output.type <= 3;
  if (cased !== inCased) {
    casedStarts.push(c.input.from);
    inCased = cased;
  }
}
const lower = [];
for (const c of table.cases) {
  if (!c.name.startsWith('lower-')) continue;
  lower.push([c.input.codePoint, c.output.lower]);
}
const out = `// Generated by scripts/gen-answer-unicode.mjs from test/golden/answers/unicode-android-table.json. Do not edit.
// Android 16 (ICU 76.1, Unicode 16.0): Character.getType grouped into cleanString's classes, and
// Character.toLowerCase for every code point whose lower case differs.

/** Range starts (ascending); range i runs up to CLASS_STARTS[i + 1] - 1. */
export const CLASS_STARTS: readonly number[] = ${JSON.stringify(starts)};
/** 0 keep, 1 space (type 0 or SPACE_SEPARATOR..SURROGATE), 2 replace (DECIMAL_DIGIT_NUMBER or >= DASH_PUNCTUATION). */
export const CLASS_CODES: readonly number[] = ${JSON.stringify(classes)};
/** Alternating starts of letter-case ranges: [first cased, first not cased, next cased, ...]. */
export const LETTER_CASE_STARTS: readonly number[] = ${JSON.stringify(casedStarts)};
/** [code point, lower case] pairs. */
export const LOWER_PAIRS: readonly (readonly [number, string])[] = ${JSON.stringify(lower)};
`;
writeFileSync('src/core/answer/unicodeData.ts', out);
console.log(`classes: ${starts.length} ranges, lower: ${lower.length} pairs`);
