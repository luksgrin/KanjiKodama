package com.smouldering_durtles.wk.local;

import android.content.Context;
import android.database.Cursor;

import androidx.sqlite.db.SupportSQLiteDatabase;

import com.smouldering_durtles.wk.db.AppDatabase;
import com.smouldering_durtles.wk.util.Logger;

import java.io.File;
import java.io.FileOutputStream;
import java.io.InputStream;
import java.io.OutputStream;
import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;

/**
 * Imports the bundled content database (assets/wk-content.db, generated by
 * tools/build_wk_asset.py) into the app database on first launch.
 */
public final class LocalContent {
    private static final Logger LOGGER = Logger.get(LocalContent.class);
    public static final String ASSET = "wk-content.db";

    private LocalContent() {
        //
    }

    /** True when the subject table already holds content. */
    public static boolean hasContent(final AppDatabase db) {
        try (final Cursor c = db.getOpenHelper().getReadableDatabase().query("SELECT COUNT(*) FROM subject")) {
            return c.moveToFirst() && c.getLong(0) > 0;
        }
    }

    /** True when the APK carries the content asset (builds without the private dump do not). */
    public static boolean assetPresent(final Context context) {
        try (final InputStream ignored = context.getAssets().open(ASSET)) {
            return true;
        } catch (final Exception e) {
            return false;
        }
    }

    /**
     * Copy subjects and SRS systems from the asset into the app database if it is empty.
     *
     * @return the number of subjects imported (0 when nothing was done)
     */
    public static int importIfNeeded(final Context context, final AppDatabase db) {
        if (hasContent(db) || !assetPresent(context)) {
            return 0;
        }
        final File file = new File(context.getCacheDir(), ASSET);
        try {
            try (final InputStream in = context.getAssets().open(ASSET); final OutputStream out = new FileOutputStream(file)) {
                final byte[] buf = new byte[1 << 16];
                int n;
                while ((n = in.read(buf)) > 0) {
                    out.write(buf, 0, n);
                }
            }
            final SupportSQLiteDatabase sql = db.getOpenHelper().getWritableDatabase();
            sql.execSQL("ATTACH DATABASE '" + file.getAbsolutePath().replace("'", "''") + "' AS src");
            try {
                copyTable(sql, "srs_system");
                copyTable(sql, "subject");
            } finally {
                sql.execSQL("DETACH DATABASE src");
            }
            final int count;
            try (final Cursor c = sql.query("SELECT COUNT(*) FROM subject")) {
                count = c.moveToFirst() ? c.getInt(0) : 0;
            }
            LOGGER.info("Imported %d subjects from bundled content", count);
            return count;
        } catch (final Exception e) {
            LOGGER.error(e, "Importing bundled content failed");
            return 0;
        } finally {
            //noinspection ResultOfMethodCallIgnored
            file.delete();
        }
    }

    private static List<String> columns(final SupportSQLiteDatabase sql, final String schema, final String table) {
        final List<String> result = new ArrayList<>();
        try (final Cursor c = sql.query("PRAGMA " + schema + ".table_info(`" + table + "`)")) {
            final int idx = c.getColumnIndexOrThrow("name");
            while (c.moveToNext()) {
                result.add(c.getString(idx));
            }
        }
        return result;
    }

    private static void copyTable(final SupportSQLiteDatabase sql, final String table) {
        final Set<String> shared = new LinkedHashSet<>(columns(sql, "main", table));
        shared.retainAll(columns(sql, "src", table));
        final StringBuilder cols = new StringBuilder();
        for (final String col: shared) {
            if (cols.length() > 0) {
                cols.append(", ");
            }
            cols.append('`').append(col).append('`');
        }
        sql.execSQL("INSERT OR REPLACE INTO main.`" + table + "` (" + cols + ") SELECT " + cols + " FROM src.`" + table + "`");
    }
}
